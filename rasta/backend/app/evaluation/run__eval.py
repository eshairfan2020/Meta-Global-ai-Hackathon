"""Run the synthetic evaluation set through the REAL local model and write a results report.

    cd backend
    python -m evaluation.run_eval                 # English explanations, model from .env
    python -m evaluation.run_eval --lang ur       # Roman Urdu explanations
    python -m evaluation.run_eval --limit 6       # quick smoke run
    python -m evaluation.run_eval --out ../docs/eval-results-3b.md

CPU inference is slow: expect roughly (number of cases x model latency). Nothing here is mocked.
Results describe THIS small synthetic set only; they are not an accuracy claim."""
import argparse
import asyncio
import json
import statistics
from datetime import datetime, timezone
from pathlib import Path

from app.config import load_settings
from app.errors import AppError
from app.pipeline import run_pipeline
from app.providers.base import AnalysisProvider
from app.providers.ollama import OllamaAnalysisProvider
from app.schemas import Language, RiskBand

from .cases import CASES

FLAGGED = {RiskBand.high_concern.value, RiskBand.some_concern.value}


async def evaluate(provider: AnalysisProvider, cases: list[dict], language: Language, progress=None) -> list[dict]:
    rows = []
    for i, c in enumerate(cases, 1):
        row = {"id": c["id"], "expected": c["expected"], "code": c["code"]}
        try:
            r = await run_pipeline(provider, c["text"], language)
            row.update(status="ok", raw_band=r.raw_band.value, final_band=r.assessment.risk_band.value,
                       category=r.assessment.scam_category.value, rule_adjusted=r.rule_adjusted,
                       rules_triggered=r.rules_triggered, attempts=r.out.attempts,
                       quotes_removed=r.quotes_removed, latency_ms=r.out.latency_ms)
        except AppError as e:
            row.update(status=e.code)
        rows.append(row)
        if progress:
            progress(i, len(cases), row)
    return rows


def _frac(n: int, d: int) -> str:
    return f"{n}/{d}" if d else "n/a"


def summarize(rows: list[dict]) -> dict:
    ok = [r for r in rows if r["status"] == "ok"]
    lat = sorted(r["latency_ms"] for r in ok if r.get("latency_ms") is not None)
    scam = [r for r in ok if r["expected"] == "scam"]
    code = [r for r in ok if r["code"]]
    benign = [r for r in ok if r["expected"] == "benign"]
    errors: dict[str, int] = {}
    for r in rows:
        if r["status"] != "ok":
            errors[r["status"]] = errors.get(r["status"], 0) + 1
    bands: dict[str, int] = {}
    for r in ok:
        bands[r["final_band"]] = bands.get(r["final_band"], 0) + 1
    return {
        "n": len(rows), "ok": len(ok), "errors": errors,
        "first_try_valid": _frac(sum(r["attempts"] == 1 for r in ok), len(ok)),
        "quotes_removed_total": sum(r["quotes_removed"] for r in ok),
        "latency_median_s": round(statistics.median(lat) / 1000, 1) if lat else None,
        "latency_p90_s": round(lat[min(len(lat) - 1, int(len(lat) * 0.9))] / 1000, 1) if lat else None,
        "scam_n": len(scam),
        "scam_missed_model": _frac(sum(r["raw_band"] == "insufficient_evidence" for r in scam), len(scam)),
        "scam_missed_final": _frac(sum(r["final_band"] == "insufficient_evidence" for r in scam), len(scam)),
        "code_high_model": _frac(sum(r["raw_band"] == "high_concern" for r in code), len(code)),
        "code_high_final": _frac(sum(r["final_band"] == "high_concern" for r in code), len(code)),
        "rule_adjusted": _frac(sum(r["rule_adjusted"] for r in ok), len(ok)),
        "benign_false_alarm_model": _frac(sum(r["raw_band"] in FLAGGED for r in benign), len(benign)),
        "benign_false_alarm_final": _frac(sum(r["final_band"] in FLAGGED for r in benign), len(benign)),
        "final_bands": bands,
    }


def to_markdown(s: dict, rows: list[dict], model: str, language: str) -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out = [
        f"# Evaluation results — {model} ({language})",
        "",
        f"Generated by `python -m evaluation.run_eval` on {stamp}. **Real local inference, no mocks.**",
        f"n = {s['n']} synthetic messages written by the developer. This is a small smoke-level check,",
        "**not** an accuracy claim, and not representative of real scams.",
        "",
        "| Metric | Result |", "|---|---|",
        f"| Completed / total | {s['ok']}/{s['n']} (technical errors: {s['errors'] or 'none'}) |",
        f"| Valid structured output on first try | {s['first_try_valid']} |",
        f"| Model quotes removed (not found in message) | {s['quotes_removed_total']} |",
        f"| Latency median / p90 | {s['latency_median_s']} s / {s['latency_p90_s']} s |",
        f"| Scam messages rated *insufficient evidence* — model alone | {s['scam_missed_model']} |",
        f"| Scam messages rated *insufficient evidence* — after safety rule | {s['scam_missed_final']} |",
        f"| Code-request messages rated *high concern* — model alone | {s['code_high_model']} |",
        f"| Code-request messages rated *high concern* — after safety rule | {s['code_high_final']} |",
        f"| Results changed by the safety rule | {s['rule_adjusted']} |",
        f"| Benign messages flagged (some/high concern) — model alone | {s['benign_false_alarm_model']} |",
        f"| Benign messages flagged — final | {s['benign_false_alarm_final']} |",
        f"| Final band distribution | {s['final_bands']} |",
        "", "## Per-message results", "",
        "| id | expected | model band | final band | rule | attempts | quotes removed | latency (s) |", "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        if r["status"] != "ok":
            out.append(f"| {r['id']} | {r['expected']} | ERROR: {r['status']} | | | | | |")
        else:
            lat = round(r["latency_ms"] / 1000, 1) if r.get("latency_ms") is not None else ""
            out.append(f"| {r['id']} | {r['expected']} | {r['raw_band']} | {r['final_band']} | {'raised' if r['rule_adjusted'] else '-'} | {r['attempts']} | {r['quotes_removed']} | {lat} |")
    return "\n".join(out) + "\n"


async def _main(args) -> None:
    settings = load_settings()
    if settings.ai_provider != "ollama":
        raise SystemExit("Set AI_PROVIDER=ollama: the evaluation only makes sense with the real model.")
    provider = OllamaAnalysisProvider(settings)
    st = await provider.status()
    if st.state != "ready":
        raise SystemExit(f"Model not ready: {st.state} — {st.detail}")
    cases = CASES[: args.limit] if args.limit else CASES
    lang = Language(args.lang)
    print(f"Model {settings.ollama_model}; {len(cases)} cases; explanations in {lang.value}. This can take a while on CPU.")
    rows = await evaluate(provider, cases, lang,
                          progress=lambda i, n, r: print(f"[{i}/{n}] {r['id']}: {r.get('raw_band', r['status'])} -> {r.get('final_band', '')} "
                                                         f"{(r.get('latency_ms') or 0) / 1000:.1f}s"))
    summary = summarize(rows)
    md = to_markdown(summary, rows, settings.ollama_model, lang.value)
    out = Path(args.out or f"../docs/eval-results-{settings.ollama_model.replace(':', '-')}-{lang.value}.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(md, encoding="utf-8")
    out.with_suffix(".json").write_text(json.dumps({"summary": summary, "rows": rows}, indent=2), encoding="utf-8")
    print(md)
    print(f"Wrote {out} and {out.with_suffix('.json')}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--lang", choices=["en", "ur"], default="en")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--out", default="")
    asyncio.run(_main(ap.parse_args()))
