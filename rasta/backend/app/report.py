from html import escape as e

from .schemas import CaseView, RiskBand

BAND = {
    RiskBand.high_concern: "High concern",
    RiskBand.some_concern: "Some concern",
    RiskBand.insufficient_evidence: "Insufficient evidence (this is not a safety guarantee)",
}
STATUS = {
    "not_checked": "Not checked",
    "attempting_independent_contact": "Attempting independent contact",
    "user_recorded_confirmation": "User recorded: confirmed",
    "user_recorded_denial": "User recorded: denied",
    "inconclusive": "Inconclusive",
}
STYLE = """body{font-family:system-ui,Segoe UI,Arial,sans-serif;color:#0f172a;max-width:760px;margin:24px auto;padding:0 16px;line-height:1.45}
h1{font-size:22px;margin:0}h2{font-size:15px;margin:22px 0 6px;border-bottom:1px solid #cbd5e1;padding-bottom:4px;color:#0f766e}
.meta td{padding:2px 12px 2px 0;vertical-align:top}.q{font-style:italic;background:#f1f5f9;padding:2px 6px;border-radius:4px}
.tag{display:inline-block;border:1px solid #94a3b8;border-radius:4px;padding:1px 6px;font-size:12px;margin-left:6px}
footer{margin-top:28px;border-top:1px solid #cbd5e1;padding-top:8px;font-size:12px;color:#475569}"""


def _yn(v: bool) -> str:
    return "Yes" if v else "No"


def render_report(c: CaseView) -> str:
    a, f = c.assessment, c.assessment.observed_facts
    if c.inference == "real":
        infer = f"Real local inference — Meta Llama via Ollama, model tag: {c.model}" + (
            f" (latency {c.latency_ms} ms)" if c.latency_ms is not None else "")
    else:
        infer = "Predefined sample assessment (mock mode). Not generated by a model."
    signals = "".join(
        f"<li><b>{e(s.label)}</b><br><span class='q'>“{e(s.source_quote)}”</span><br>{e(s.explanation)}</li>"
        for s in a.warning_signals
    ) or "<li>No warning signals with verified quotes.</li>"
    actions = "".join(f"<li>{e(x)}</li>" for x in a.recommended_actions) or "<li>—</li>"
    timeline = "".join(
        f"<li>{e(ev.timestamp)} — {e(STATUS[ev.status.value])}</li>" for ev in c.verification.events
    ) or "<li>No verification outcome recorded.</li>"
    notes = []
    if c.rule_adjusted:
        notes.append("A built-in rule (plain code, not the model) raised this result because the message asks you to share a login code.")
    if c.redactions:
        notes.append(f"{c.redactions} sensitive-looking value(s) were masked before analysis (best effort).")
    if c.quotes_removed:
        notes.append(f"{c.quotes_removed} model quotation(s) were removed because they were not found in the input.")
    if c.amount_cleared:
        notes.append("A model-reported amount was removed because it did not appear in the input.")
    notes_html = "".join(f"<li>{e(n)}</li>" for n in notes)
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Rasta incident record {e(c.case_id)}</title>
<style>{STYLE}</style></head><body>
<h1>Rasta — Incident record</h1><div>Pause. Verify. Proceed.</div>
<table class="meta"><tr><td>Case ID</td><td>{e(c.case_id)}</td></tr>
<tr><td>Created (UTC)</td><td>{e(c.created_at)}</td></tr>
<tr><td>Input</td><td>{"Synthetic example — not a real incident." if c.is_synthetic else "User-pasted text (not stored by this report)."}</td></tr>
<tr><td>Provider</td><td>{e(c.provider)}</td></tr>
<tr><td>Analysis</td><td>{e(infer)}</td></tr>
<tr><td>Output language</td><td>{"English" if c.language.value == "en" else "Roman Urdu"}</td></tr></table>
<h2>Assessment</h2><p><b>{e(BAND[a.risk_band])}</b><span class="tag">{e(a.scam_category.value)}</span></p>
<h2>Observed facts</h2><table class="meta">
<tr><td>Claimed identity</td><td>{e(f.claimed_identity or "—")}</td></tr>
<tr><td>Requested action</td><td>{e(f.requested_action or "—")}</td></tr>
<tr><td>Amount</td><td>{e(f.amount or "—")}</td></tr>
<tr><td>Urgency present</td><td>{_yn(f.urgency_present)}</td></tr>
<tr><td>Secrecy present</td><td>{_yn(f.secrecy_present)}</td></tr>
<tr><td>Verification code requested</td><td>{_yn(f.verification_code_requested)}</td></tr></table>
<h2>Warning signals</h2><ul>{signals}</ul>
<h2>Uncertainty</h2><p>{e(a.uncertainty)}</p>
<h2>Recommended actions</h2><ul>{actions}</ul>
<h2>Suggested safe reply</h2><p class="q">{e(a.safe_reply)}</p>
<h2>Verification timeline</h2><ul>{timeline}</ul>
<p><i>Recorded by the user; not independently verified by Rasta.</i></p>
{"<h2>Processing notes</h2><ul>" + notes_html + "</ul>" if notes else ""}
<footer>Advisory incident record. Not a forensic report, official complaint, identity verification, or proof of fraud.</footer>
</body></html>"""
